//! Extensions that ship inside oxplow, from the repo's `extensions/<name>/`
//! folder: compiled in by a release build, read from that folder once per
//! process by a debug build (and its tests), so editing one never
//! recompiles this crate. They load exactly like project extensions (same
//! format, same loader) and their names are reserved. Their shipped copies
//! run unless a dev build is asked to run them from their sources
//! (`enableBundledExtensions: false`, [`shipped`]). See
//! `.context/extensions.md`.

/// A bundled extension's files, as `(path inside its folder, bytes)`.
pub type Files = &'static [(&'static str, &'static [u8])];

/// One bundled extension: its name and its files as
/// `(path inside the extension folder, bytes)` — bytes, so a custom
/// component's assets ship as they are.
pub struct BundledExtension {
    pub name: &'static str,
    /// Its files ([`BundledExtension::files`]).
    pub files: fn() -> Files,
    /// oxplow itself relies on it (`oxplow-foundation`, its own
    /// commands): it can't be disabled or removed.
    pub required: bool,
}

impl BundledExtension {
    /// Its files: the folder's (its build's output included, its
    /// `build.exclude` and dot entries left out).
    pub fn files(&self) -> Files {
        (self.files)()
    }

    /// The file at `path` in it, as text; `None` when it isn't there or
    /// isn't UTF-8.
    pub fn file(&self, path: &str) -> Option<&'static str> {
        self.bytes(path).and_then(|b| std::str::from_utf8(b).ok())
    }

    /// The file at `path` in it.
    pub fn bytes(&self, path: &str) -> Option<&'static [u8]> {
        self.files()
            .iter()
            .find(|(p, _)| *p == path)
            .map(|(_, f)| *f)
    }
}

/// Each bundled extension's files, generated by `build.rs` from its
/// folder (`extensions/<name>/`, its build's output included).
#[cfg(not(debug_assertions))]
mod generated {
    include!(concat!(env!("OUT_DIR"), "/bundled_files.rs"));
}

/// Each bundled extension's files, read from its folder the first time
/// they're asked for — what `build.rs` would have compiled in, without
/// making this crate depend on them. `build.rs` still builds a missing
/// output (`dist/`); a later source change reaches a running dev oxplow
/// through deploy, not through this copy.
#[cfg(debug_assertions)]
mod generated {
    use super::Files;
    use std::sync::OnceLock;

    pub fn oxplow_foundation() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxplow-foundation"))
    }

    pub fn oxplow_bundled() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxplow-bundled"))
    }

    /// `extensions/<name>/`'s files, kept for the life of the process.
    fn read(name: &str) -> Files {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../extensions")
            .join(name);
        let files = crate::extension_store::shipped_files(&dir)
            .unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()));
        let files: Vec<(&'static str, &'static [u8])> = files
            .into_iter()
            .map(|(rel, bytes)| {
                (
                    &*Box::leak(rel.into_boxed_str()),
                    &*Box::leak(bytes.into_boxed_slice()),
                )
            })
            .collect();
        Box::leak(files.into_boxed_slice())
    }
}

pub const BUNDLED: &[BundledExtension] = &[
    BundledExtension {
        name: "oxplow-foundation",
        files: generated::oxplow_foundation,
        required: true,
    },
    BundledExtension {
        name: "oxplow-bundled",
        files: generated::oxplow_bundled,
        required: false,
    },
];

pub fn find(name: &str) -> Option<&'static BundledExtension> {
    BUNDLED.iter().find(|b| b.name == name)
}

/// The copy of `name` built into oxplow, when it runs from that copy: not
/// when `settings` run oxplow's own extensions from their sources
/// (`enableBundledExtensions: false`, a dev build). `find` is the name.
pub fn shipped(
    name: &str,
    settings: &oxplow_config::ExtensionSettings,
) -> Option<&'static BundledExtension> {
    (!settings.bundled_from_sources)
        .then(|| find(name))
        .flatten()
}

/// Whether oxplow relies on extension `name` (it can't be disabled).
pub fn is_required(name: &str) -> bool {
    find(name).is_some_and(|b| b.required)
}

pub fn is_reserved(name: &str) -> bool {
    find(name).is_some()
}

