    /// The `runs` page: per extension, the last week's runs, failures,
    /// denials, mean CPU and model calls, the ones needing attention first.
    #[tokio::test(flavor = "multi_thread")]
    async fn the_runs_page_counts_each_extensions_week() {
        let f = crate::test_fixtures::services_with_effort().await;
        // Only these runs: the fixture's own (foundation's
        // `oxplow.effort.open`) are runs too.
        f.svc
            .db
            .transaction(|tx| {
                tx.execute("DELETE FROM extension_run", [])
                    .map_err(oxplow_db::map_sql_err)
                    .map(|_| ())
            })
            .await
            .unwrap();
        // (extension, outcome, days ago, cpu ms, model calls)
        let runs: [(&str, &str, i64, i64, i64); 6] = [
            ("acme", "ok", 1, 10, 0),
            ("acme", "failed", 2, 30, 2),
            ("acme", "denied", 3, 20, 0),
            ("acme", "ok", 8, 999, 9), // a week and a day ago: out
            ("beta", "ok", 0, 5, 0),
            ("beta", "ok", 4, 7, 0),
        ];
        f.svc
            .db
            .transaction(move |tx| {
                for (i, (ext, outcome, days, cpu, ai)) in runs.iter().enumerate() {
                    tx.execute(
                        "INSERT INTO extension_run
                           (run_id, extension, contribution, kind, actor_kind, actor, mode,
                            started_at, finished_at, outcome, wall_ms, cpu_ms, peak_bytes,
                            ai_calls, scopes_json, decisions_json)
                         VALUES (?1, ?2, ?3, 'collector', 'system', 'system', 'external',
                            strftime('%Y-%m-%dT%H:%M:%fZ', 'now', '-' || ?4 || ' days'),
                            strftime('%Y-%m-%dT%H:%M:%fZ', 'now', '-' || ?4 || ' days'),
                            ?5, 1, ?6, 0, ?7, '{}', '[]')",
                        rusqlite::params![
                            format!("run{i}"),
                            ext,
                            oxplow_domain::uri::build::keyed(
                                oxplow_domain::uri::resources::COLLECTOR,
                                &format!("{ext}/pull")
                            ),
                            days,
                            outcome,
                            cpu,
                            ai
                        ],
                    )
                    .map_err(oxplow_db::map_sql_err)?;
                }
                Ok(())
            })
            .await
            .unwrap();
        let rows = run_bundled_page(&f, "oxplow-bundled/runs", &[]).await;
        // Each extension links to its runs, one by one.
        let runs_of = |ext: &str| {
            oxplow_domain::uri::build::page_uri("extension-runs", &[("extension", ext)])
        };
        assert_eq!(
            rows,
            serde_json::json!([
                ["acme", runs_of("acme"), 3, 1, 1, 20.0, 2],
                ["beta", runs_of("beta"), 2, 0, 0, 6.0, 0]
            ])
        );
        let detail = run_bundled_page_with(
            &f,
            "oxplow-bundled/extension-runs",
            &[("extension", oxplow_db::SqlCell::Text("acme".into()))],
        )
        .await;
        let outcomes: Vec<_> = detail
            .as_array()
            .unwrap()
            .iter()
            .map(|row| (row[0].clone(), row[3].clone()))
            .collect();
        // Newest first, the week and a day old run out.
        assert_eq!(
            outcomes,
            vec![
                (
                    serde_json::json!("oxplow:oxplow/collector?collector=acme/pull (collector)"),
                    serde_json::json!("ok")
                ),
                (
                    serde_json::json!("oxplow:oxplow/collector?collector=acme/pull (collector)"),
                    serde_json::json!("failed")
                ),
                (
                    serde_json::json!("oxplow:oxplow/collector?collector=acme/pull (collector)"),
                    serde_json::json!("denied")
                ),
            ]
        );
    }

