//! Extensions that ship inside oxplow, from the repo's `extensions/<name>/`
//! folder: compiled in by a release build, read from that folder once per
//! process by a debug build (and its tests), so editing one never
//! recompiles this crate. They load exactly like project extensions (same
//! format, same loader) and their names are reserved. Their shipped copies
//! run, except that a dev build runs each one whose source the project has
//! from that source (`ExtensionSettings::from_source`, [`shipped`]). See
//! `.context/extensions-bundled.md`.

/// A bundled extension's files, as `(path inside its folder, bytes)`.
pub type Files = &'static [(&'static str, &'static [u8])];

/// One bundled extension: its name and its files as
/// `(path inside the extension folder, bytes)` — bytes, so a custom
/// component's assets ship as they are.
pub struct BundledExtension {
    pub name: &'static str,
    /// Its files ([`BundledExtension::files`]).
    pub files: fn() -> Files,
    /// oxplow itself relies on it (`oxplow-foundation`, its own
    /// commands): it can't be disabled or removed.
    pub required: bool,
}

impl BundledExtension {
    /// Its files: the folder's (its build's output included, its
    /// `build.exclude` and dot entries left out).
    pub fn files(&self) -> Files {
        (self.files)()
    }

    /// The file at `path` in it, as text; `None` when it isn't there or
    /// isn't UTF-8.
    pub fn file(&self, path: &str) -> Option<&'static str> {
        self.bytes(path).and_then(|b| std::str::from_utf8(b).ok())
    }

    /// The file at `path` in it.
    pub fn bytes(&self, path: &str) -> Option<&'static [u8]> {
        self.files()
            .iter()
            .find(|(p, _)| *p == path)
            .map(|(_, f)| *f)
    }
}

/// Each bundled extension's files, generated by `build.rs` from its
/// folder (`extensions/<name>/`, its build's output included).
#[cfg(not(debug_assertions))]
mod generated {
    include!(concat!(env!("OUT_DIR"), "/bundled_files.rs"));
}

/// Each bundled extension's files, read from its folder the first time
/// they're asked for — what `build.rs` would have compiled in, without
/// making this crate depend on them. `build.rs` still builds a missing
/// output (`dist/`); a later source change reaches a running dev oxplow
/// through deploy, not through this copy.
#[cfg(debug_assertions)]
mod generated {
    use super::Files;
    use std::sync::OnceLock;

    pub fn oxplow_foundation() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxplow-foundation"))
    }

    pub fn oxplow_bundled() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxplow-bundled"))
    }

    pub fn oxtask() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxtask"))
    }

    pub fn oxwiki() -> Files {
        static FILES: OnceLock<Files> = OnceLock::new();
        FILES.get_or_init(|| read("oxwiki"))
    }

    /// `extensions/<name>/`'s files, kept for the life of the process.
    fn read(name: &str) -> Files {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../extensions")
            .join(name);
        let files = crate::extension::extension_store::shipped_files(&dir)
            .unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()));
        let files: Vec<(&'static str, &'static [u8])> = files
            .into_iter()
            .map(|(rel, bytes)| {
                (
                    &*Box::leak(rel.into_boxed_str()),
                    &*Box::leak(bytes.into_boxed_slice()),
                )
            })
            .collect();
        Box::leak(files.into_boxed_slice())
    }
}

pub const BUNDLED: &[BundledExtension] = &[
    BundledExtension {
        name: "oxplow-foundation",
        files: generated::oxplow_foundation,
        required: true,
    },
    BundledExtension {
        name: "oxplow-bundled",
        files: generated::oxplow_bundled,
        required: false,
    },
    BundledExtension {
        name: "oxtask",
        files: generated::oxtask,
        required: false,
    },
    BundledExtension {
        name: "oxwiki",
        files: generated::oxwiki,
        required: false,
    },
];

pub fn find(name: &str) -> Option<&'static BundledExtension> {
    BUNDLED.iter().find(|b| b.name == name)
}

/// The copy of `name` built into oxplow, when it runs from that copy: not
/// when `settings` run it from its source (a dev build with the source
/// here, `ExtensionSettings::from_source`). `find` is the name.
pub fn shipped(
    name: &str,
    settings: &oxplow_config::ExtensionSettings,
) -> Option<&'static BundledExtension> {
    (!settings.from_source.contains(name))
        .then(|| find(name))
        .flatten()
}

/// Whether oxplow relies on extension `name` (it can't be disabled).
pub fn is_required(name: &str) -> bool {
    find(name).is_some_and(|b| b.required)
}

pub fn is_reserved(name: &str) -> bool {
    find(name).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// What oxplow ships runs in other people's projects: its text and
    /// examples must not name this repository's docs or build.
    #[test]
    fn shipped_text_never_names_the_checkout() {
        let needles = [".context/", "crates/", "cargo "];
        let mut hits = Vec::new();
        for b in BUNDLED {
            for (path, bytes) in b.files() {
                // Fixtures are test data, and `dist/` is built output.
                if path.starts_with("fixtures/") || path.starts_with("dist/") {
                    continue;
                }
                let Ok(text) = std::str::from_utf8(bytes) else {
                    continue;
                };
                for (n, line) in text.lines().enumerate() {
                    // A `run_patterns:` entry names the tools whose commands
                    // count as a run (`cargo test`): that is data about
                    // other people's projects, not this checkout's build.
                    if *path == "extension.yaml" && line.trim_start().starts_with("- { kind: ") {
                        continue;
                    }
                    for needle in needles {
                        if line.contains(needle) {
                            hits.push(format!("{}/{path}:{}: `{needle}`", b.name, n + 1));
                        }
                    }
                }
            }
        }
        assert!(hits.is_empty(), "{}", hits.join("\n"));
    }

    /// `oxtask` and `oxwiki` ship on by default: both are found and load
    /// clean and activate clean with bundled on; with bundled off they are
    /// held (listed with why), not a boot failure.
    #[tokio::test(flavor = "multi_thread")]
    async fn oxtask_and_oxwiki_are_on_by_default_and_need_bundled() {
        for name in ["oxtask", "oxwiki"] {
            assert!(find(name).is_some(), "{name} ships");
            assert!(!is_required(name), "{name} is optional");
        }
        assert!(oxplow_config::DEFAULT_EXTENSIONS.contains(&"oxtask"));
        assert!(oxplow_config::DEFAULT_EXTENSIONS.contains(&"oxwiki"));
        let project = |yaml: &str| {
            let dir = tempfile::tempdir().unwrap();
            crate::test_fixtures::init_git_repo(dir.path());
            std::fs::create_dir_all(dir.path().join(".oxplow")).unwrap();
            std::fs::write(dir.path().join(".oxplow/project.yaml"), yaml).unwrap();
            dir
        };

        // The defaults: both are on and running.
        let dir = project("");
        let loaded = crate::extension::extensions::load_extensions(dir.path());
        for (name, namespace) in [("oxtask", "oxtask"), ("oxwiki", "oxwiki")] {
            let ext = loaded.iter().find(|e| e.name == name).expect(name);
            assert!(ext.errors.is_empty(), "{name}: {:?}", ext.errors);
            assert_eq!(ext.namespace, namespace);
            assert_eq!(ext.requires, ["oxplow-bundled"]);
            assert!(ext.enabled, "{name} by default");
        }
        let svc = crate::Services::in_memory(dir.path()).await.unwrap();
        svc.streams.ensure_primary().await.unwrap();
        crate::test_fixtures::activate(&svc).await;
        let runs = |svc: &crate::Services, name: &str| {
            svc.extension_catalog
                .active()
                .is_some_and(|s| s.extensions().iter().any(|e| e.name == name && e.enabled))
        };
        assert!(runs(&svc, "oxtask") && runs(&svc, "oxwiki"));

        // Listed, with bundled on: both activate with nothing held.
        let dir = project(
            "oxplow.extensions.oxplow-bundled.enabled: true\noxplow.extensions.oxtask.enabled: true\noxplow.extensions.oxwiki.enabled: true\n",
        );
        let svc = crate::Services::in_memory(dir.path()).await.unwrap();
        svc.streams.ensure_primary().await.unwrap();
        crate::test_fixtures::activate(&svc).await;
        assert!(runs(&svc, "oxtask") && runs(&svc, "oxwiki"));

        // On, with bundled off: held, and oxplow still boots.
        let dir = project(
            "oxplow.extensions.oxtask.enabled: true\noxplow.extensions.oxwiki.enabled: true\noxplow.extensions.oxplow-bundled.enabled: false\n",
        );
        let svc = crate::Services::in_memory(dir.path()).await.unwrap();
        svc.streams.ensure_primary().await.unwrap();
        let problems = crate::test_fixtures::activate_with_problems(&svc).await;
        assert!(!runs(&svc, "oxtask") && !runs(&svc, "oxwiki"));
        for name in ["oxtask", "oxwiki"] {
            assert!(
                problems
                    .get(name)
                    .is_some_and(|p| p.iter().any(|d| d.render("").contains("oxplow-bundled"))),
                "{name} is held for bundled: {problems:?}"
            );
        }
        assert!(runs(&svc, "oxplow-foundation"));
    }

    /// The shipped default configuration (oxwiki on, core's built-in standing
    /// down) keeps a page end to end: a write is a file and a row, a read
    /// answers its body, a link from one page to another resolves and is
    /// found, a dangling one is refused, and the page is searchable.
    #[tokio::test(flavor = "multi_thread")]
    async fn the_default_configuration_writes_reads_links_and_searches_a_page() {
        let dir = tempfile::tempdir().unwrap();
        crate::test_fixtures::init_git_repo(dir.path());
        let svc = crate::Services::in_memory(dir.path()).await.unwrap();
        svc.streams.ensure_primary().await.unwrap();
        crate::test_fixtures::activate(&svc).await;
        let run = |name: &'static str, input: serde_json::Value| {
            let svc = svc.clone();
            async move {
                svc.commands
                    .run(&oxplow_domain::Actor::Human, name, input, true)
                    .await
            }
        };

        // Write: the file is in the primary's folder, the answer names the page.
        let first = run(
            "oxwiki.page.write",
            serde_json::json!({ "title": "Gears", "body": "# Gears\n\nThe sprocket turns.\n" }),
        )
        .await
        .unwrap();
        let page = first.result["result"]["page"]
            .as_str()
            .unwrap_or_else(|| panic!("{first:?}"))
            .to_string();
        assert_eq!(page, "oxplow:oxplow/knowledge?id=gears&store=oxwiki");
        assert!(dir.path().join(".oxplow/oxwiki/gears.md").is_file());

        // Read: oxplow_read's row has the body, through the resource's own dataset.
        let read = crate::ref_read::read(&svc, &page, &crate::ref_read::Reader::default(), None)
            .await
            .unwrap();
        let row = read.row.expect("the page is a row");
        assert_eq!(row["title"], "Gears");
        assert!(row["body"].as_str().unwrap().contains("sprocket"));
        // It resolves as a ref too.
        let resolved = crate::ref_resolver::resolve_ref(&svc, &page).await;
        assert!(resolved.resolved, "{resolved:?}");
        assert_eq!(resolved.title.as_deref(), Some("Gears"));

        // Link: one page to another; a dangling link is refused.
        run(
            "oxwiki.page.write",
            serde_json::json!({ "id": "teeth", "body": "# Teeth\n\nSee [[gears]].\n" }),
        )
        .await
        .unwrap();
        let refused = run(
            "oxwiki.page.write",
            serde_json::json!({ "id": "bad", "body": "# Bad\n\nSee [[nowhere]].\n" }),
        )
        .await;
        assert!(refused.is_err(), "a dangling link is refused");
        let out = svc
            .sql
            .query_sql(
                "SELECT outbound_uris FROM v_oxplow_knowledge_page WHERE id = 'teeth'",
                vec![],
                None,
            )
            .await
            .unwrap();
        let outbound = format!("{:?}", out.rows);
        assert!(outbound.contains("gears"), "teeth links gears: {outbound}");

        // Search: the resource's search dataset holds the page's text.
        let out = svc
            .sql
            .query_sql(
                "SELECT uri FROM v_oxplow_search_knowledge WHERE body LIKE '%sprocket%'",
                vec![],
                None,
            )
            .await
            .unwrap();
        assert_eq!(out.rows.len(), 1, "{:?}", out.rows);
    }

    /// The `oxplow` namespace's settings hold bundled's keys (its review
    /// policy, say): with bundled off they are still a valid layer, read
    /// rather than refused, so foundation keeps running.
    #[tokio::test(flavor = "multi_thread")]
    async fn settings_stay_readable_with_bundled_off() {
        let dir = tempfile::tempdir().unwrap();
        crate::test_fixtures::init_git_repo(dir.path());
        std::fs::create_dir_all(dir.path().join(".oxplow")).unwrap();
        std::fs::write(
            dir.path().join(".oxplow/local.yaml"),
            crate::test_fixtures::optional_shipped_disabled(),
        )
        .unwrap();
        let svc = crate::Services::in_memory(dir.path()).await.unwrap();
        svc.streams.ensure_primary().await.unwrap();
        crate::test_fixtures::activate(&svc).await;
        let read = svc
            .sql
            .query_sql(
                "SELECT value, origin FROM v_config_value WHERE key = 'oxplow.struggle.repeatedEdits'",
                vec![],
                None,
            )
            .await
            .expect("the settings read with bundled off");
        let rows = serde_json::to_value(&read.rows).unwrap();
        assert_eq!(rows.as_array().map(Vec::len), Some(1), "{rows}");
        assert_eq!(rows[0][1], serde_json::json!("default"), "{rows}");
    }
}
