#[test]
fn generated_source_detected_by_header_marker() {
    // The Tauri Specta / ts-rs / protobuf convention: a do-not-edit header.
    let specta = "// This file has been generated by Tauri Specta. Do not edit this file manually.\n\nexport const x = 1;\n";
    assert!(has_generated_header(specta));
    let go = "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n";
    assert!(has_generated_header(go));
    let meta = "/* @generated */\nconst a = 1;\n";
    assert!(has_generated_header(meta));
}

/// Where generated and vendored files live is the file kinds' globs, handed
/// to the set; with none, no path is left out.
#[test]
fn a_corpus_leaves_out_the_paths_the_file_kinds_name() {
    let set = shipped().with_excluded(vec![
        "**/generated/**".into(),
        "**/*.generated.*".into(),
        "vendor/**".into(),
    ]);
    assert!(set.is_excluded("apps/desktop/src/tauri-bridge/generated/bindings.ts"));
    assert!(set.is_excluded("src/api.generated.ts"));
    assert!(set.is_excluded("vendor/lib/a.go"));
    assert!(!set.is_excluded("src/degenerated_cases.rs"));
    assert!(!set.is_excluded("src/main.rs"));
    assert!(
        !shipped().is_excluded("vendor/lib/a.go"),
        "no rules, none left out"
    );
    assert_eq!(set.excluded_globs().len(), 3);
}

#[test]
fn generated_marker_only_counts_in_the_header() {
    // "do not edit" deep in a hand-written file (say, inside a string or a
    // late comment) must not flag the whole file as generated.
    let mut src = String::from("fn main() {\n");
    for _ in 0..20 {
        src.push_str("    println!(\"x\");\n");
    }
    src.push_str("    // do not edit this constant lightly\n}\n");
    assert!(!has_generated_header(&src));
}

