SELECT h.id,
       CAST('handoff:hnd' || h.id AS TEXT) AS ref,
       h.from_thread_id,
       (SELECT t.ref FROM ref('thread') t WHERE t.id = h.from_thread_id) AS from_thread_ref,
       h.from_session_id,
       (SELECT s.ref FROM ref('agent_session') s WHERE s.id = h.from_session_id) AS from_session_ref,
       h.from_actor,
       h.to_thread_id,
       (SELECT t.ref FROM ref('thread') t WHERE t.id = h.to_thread_id) AS to_thread_ref,
       h.work_item,
       h.body,
       h.sent_at,
       h.delivered_at,
       h.delivered_to_session_id,
       h.state,
       h.settled_at,
       h.settled_by_session_id,
       h.note
FROM source('handoff') h
