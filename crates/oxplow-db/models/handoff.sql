SELECT h.id,
       CAST(uri('oxplow/handoff', 'id', 'hnd' || h.id) AS TEXT) AS uri,
       h.from_thread_id,
       (SELECT t.uri FROM ref('thread') t WHERE t.id = h.from_thread_id) AS from_thread_uri,
       h.from_session_id,
       (SELECT s.uri FROM ref('agent_session') s WHERE s.id = h.from_session_id) AS from_session_uri,
       h.from_actor,
       h.to_thread_id,
       (SELECT t.uri FROM ref('thread') t WHERE t.id = h.to_thread_id) AS to_thread_uri,
       h.work_item,
       h.body,
       h.sent_at,
       h.delivered_at,
       h.delivered_to_session_id,
       h.state,
       h.settled_at,
       h.settled_by_session_id,
       h.note
FROM source('handoff') h
